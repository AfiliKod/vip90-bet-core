// Takım adlarının çevrilmesi:
// Çoğu kulüp adı aynı kalır; ülke adı olan milli takımlar COUNTRY_MAP'den çevrilir.
export function translateTeam(name, lang) {
  if (!name || !lang) return name || '';
  const dict = COUNTRY_MAP[lang];
  if (!dict) return name;
  return dict[name] ?? name;
}

export function translateCountry(country, lang) {
  if (!country || !lang) return country || '';
  const dict = COUNTRY_MAP[lang];
  if (!dict) return country;
  return dict[country] ?? country;
}

export function translateLeague(league, lang) {
  if (!league || !lang) return league || '';
  const dict = LEAGUE_MAP[lang];
  if (!dict) return league;
  return dict[league] ?? league;
}

// "Country > League" formatını çevir
export function translateLeagueKey(key, lang) {
  if (!key || !lang) return key || '';
  if (key.includes(' > ')) {
    const idx = key.indexOf(' > ');
    const country = key.slice(0, idx);
    const league = key.slice(idx + 3);
    return `${translateCountry(country, lang)} > ${translateLeague(league, lang)}`;
  }
  return translateLeague(key, lang);
}

